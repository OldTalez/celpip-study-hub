// build-meta.js: writes js/data/meta.js, the small always-loaded summary of the big practice data. Run:  node tools/build-meta.js
// Check without writing (used by the test):  node tools/build-meta.js --check
// LEARNING NOTE (for beginners): since T-032 the big practice files (passages, explanations, model answers, words) are only
// downloaded when a screen needs them (js/loader.js). But Home, Learn and My plan still need a few facts about that data:
// the names of each skill's parts, how many tips there are, which passage ids exist and how many questions each has, and
// the id of every word card. Those facts are copied here, by this tool, from the real files, so they cannot drift apart:
// "--check" rebuilds the file in memory, compares it with the one on disk and exits 1 if they differ (the e2e test does
// the same comparison inside the browser). If you add a passage or a word, run this tool again and commit meta.js.
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.join(__dirname, "..");
const DATA = path.join(ROOT, "js", "data");
const OUT = path.join(DATA, "meta.js");
// The same order index.html used to load them (pools before the files that gather them).
const ORDER = ["listening_pool_1", "listening_pool_2", "listening_pool_3", "reading_pool_1", "reading_pool_2",
  "writing_speaking_pool", "listening", "reading", "writing", "speaking"];

function buildMeta() {
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  vm.runInContext(ORDER.map(f => fs.readFileSync(path.join(DATA, f + ".js"), "utf8")).join("\n") +
    "\n;var __out = { listening: LISTENING_DATA, reading: READING_DATA, writing: WRITING_DATA, speaking: SPEAKING_DATA };", sandbox);
  vm.runInContext(fs.readFileSync(path.join(DATA, "new", "vocab.js"), "utf8"), sandbox);
  const d = sandbox.__out;
  const passages = {};
  ["listening", "reading"].forEach(k => {
    passages[k] = {};
    d[k].passages.forEach(p => { passages[k][p.id] = [p.partNum, p.questions.length]; }); // id -> [part number, question count]
  });
  return {
    overview: { listening: d.listening.overview, reading: d.reading.overview, writing: d.writing.overview, speaking: d.speaking.overview },
    passages,
    vocabIds: sandbox.window.CELPIP_VOCAB.map(v => v.id)
  };
}

function render(meta) {
  return "// LEARNING NOTE (for beginners): this small file is always loaded (index.html). It is a SUMMARY of the big practice files,\n" +
    "// which download only when a screen needs them (js/loader.js). It holds: each skill's overview (part names, tips), which\n" +
    "// passages exist (id -> [part number, question count]) and the id of every word card. Home, Learn and My plan read it.\n" +
    "// GENERATED by tools/build-meta.js from the real data files. Do not edit by hand: run  node tools/build-meta.js  after the data changes.\n" +
    "window.CELPIP_META = " + JSON.stringify(meta) + ";\n";
}

const text = render(buildMeta());
if (process.argv.includes("--check")) {
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (now !== text) { console.error("meta.js is out of date: run  node tools/build-meta.js"); process.exit(1); }
  console.log("meta.js matches the data (" + text.length + " bytes)");
} else {
  fs.writeFileSync(OUT, text);
  console.log("wrote js/data/meta.js (" + text.length + " bytes)");
}
